/**
 * \brief MP3初始化
 */
void app_mp3_init(void);

/**
 * @brief 调整音量
 * @return 无
 */
void app_mp3_adjust_volume(void);

/**
 * @brief 设置音量（由 M 指令调用）；M 指令查询时若最近一次为 M 设置则返回此音量
 * @param volume 音量 0~30
 */
void app_mp3_set_volume(uint8_t volume);

/**
 * @brief 由 ADC/事件处理设置音量；M 指令查询时若最近一次为 ADC 则返回此音量
 * @param volume 音量 0~30
 */
void app_mp3_set_volume_from_adc(uint8_t volume);

/**
 * @brief 获取音量（供 M 指令查询）：按标志位返回 ADC 或 M 指令对应的音量
 * @return 音量 0~30
 */
uint8_t app_mp3_get_volume(void);

